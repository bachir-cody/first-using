const SUPPORTED_LANGS = ["en", "fr", "ar"];
const DEFAULT_LANG = "ar";
const STORAGE_KEY = "rayspub_lang";

function getSavedLang() {
    try {
        const saved = window.localStorage.getItem(STORAGE_KEY);
        if (saved && SUPPORTED_LANGS.includes(saved)) return saved;
    } catch (e) {
        /* localStorage may be unavailable — fall back silently */
    }
    return DEFAULT_LANG;
}

function saveLang(lang) {
    try {
        window.localStorage.setItem(STORAGE_KEY, lang);
    } catch (e) {
        /* ignore */
    }
}

function applyLanguage(lang) {
    if (!SUPPORTED_LANGS.includes(lang)) lang = DEFAULT_LANG;
    const dict = translations[lang];

    // Text content / inner HTML
    document.querySelectorAll("[data-i18n]").forEach((el) => {
        const key = el.getAttribute("data-i18n");
        if (dict[key] !== undefined) {
            el.innerHTML = dict[key];
        }
    });

    // Placeholders
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
        const key = el.getAttribute("data-i18n-placeholder");
        if (dict[key] !== undefined) {
            el.setAttribute("placeholder", dict[key]);
        }
    });

    // <title>
    if (dict.meta_title) document.title = dict.meta_title;

    // Direction + font
    const isRTL = lang === "ar";
    document.documentElement.setAttribute("lang", lang);
    document.documentElement.setAttribute("dir", isRTL ? "rtl" : "ltr");
    document.body.classList.toggle("lang-ar", isRTL);

    // Active state on switcher buttons
    document.querySelectorAll(".lang-btn").forEach((btn) => {
        btn.classList.toggle("active", btn.getAttribute("data-lang") === lang);
    });

    saveLang(lang);
}

document.addEventListener("DOMContentLoaded", () => {
    document.querySelectorAll(".lang-btn").forEach((btn) => {
        btn.addEventListener("click", () => applyLanguage(btn.getAttribute("data-lang")));
    });

    applyLanguage(getSavedLang());
});
